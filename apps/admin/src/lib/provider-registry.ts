/** Server-only: reports configured/missing per secret NAME. Never returns values. */
export function secretStatus(
  names: string[],
  env: Record<string, string | undefined> = process.env,
) {
  const configured = names.filter((n) => (env[n] ?? "").trim().length > 0);
  return {
    configured,
    missing: names.filter((n) => !configured.includes(n)),
    complete: configured.length === names.length,
  };
}
